// ---------------------------------------------------------------------------
// 6) build_aggregator_input (wave_classification.py:230-284)
// ---------------------------------------------------------------------------
fn build_aggregator_input(
    params: &[f64], offset_ms: f64, rr_ms: f64, amplitude_threshold: f64,
) -> std::collections::HashMap<String, Vec<(f64, f64, f64, f64)>> {
    let mut wave_dict: std::collections::HashMap<String, Vec<(f64, f64, f64, f64)>> = std::collections::HashMap::new();
    let n_gauss = params.len() / 4;

    for i in 0..n_gauss {
        let (t0, s, a, ang) = (params[4*i], params[4*i+1], params[4*i+2], params[4*i+3]);
        if a <= amplitude_threshold { continue; }
        let region = time_to_region_label(t0, rr_ms, offset_ms);
        let w_class = unify_wave_type(region);
        wave_dict.entry(w_class).or_default().push((t0, s, a, ang));
    }

    // Sort each bucket descending by t0
    for bucket in wave_dict.values_mut() {
        bucket.sort_by(|a, b| b.0.partial_cmp(&a.0).unwrap());
    }

    // T-wave postprocessing: relabel last to "I" if separated + divergent angle
    if let Some(t_list) = wave_dict.get_mut("T") {
        if t_list.len() > 1 {
            let mut sorted = t_list.clone();
            sorted.sort_by(|a, b| b.0.partial_cmp(&a.0).unwrap());
            let last = sorted[sorted.len() - 1];
            let prev = sorted[sorted.len() - 2];
            let overlap = (last.0 - prev.0).abs() < 1.41 * (last.1 + prev.1);
            let angle_diff = (last.3 - prev.3).abs();
            if !overlap && angle_diff > 1.0 { // delta_rad=1.0
                wave_dict.entry("I".to_string()).or_default().push(last);
                sorted.pop();
                *wave_dict.get_mut("T").unwrap() = sorted;
            }
        }
    }

    // QRS postprocessing: demote first to "ST" if non-overlapping
    if let Some(qrs_list) = wave_dict.get("QRS").cloned() {
        if qrs_list.len() > 1 {
            let (t0_1, s1, _, _) = qrs_list[0];
            let (t0_2, s2, _, _) = qrs_list[1];
            let overlap = (t0_1 - t0_2).abs() < 1.41 * (s1 + s2);
            if !overlap {
                wave_dict.entry("ST".to_string()).or_default().push(qrs_list[0]);
                wave_dict.insert("QRS".to_string(), qrs_list[1..].to_vec());
            }
        }
    }

    wave_dict
}

// ---------------------------------------------------------------------------
// 7) aggregate_waves_by_type (wave_classification.py:291-386)
// ---------------------------------------------------------------------------
fn aggregate_waves_by_type(
    t_ms: &[f64], vx: &[f64], vy: &[f64],
    wave_groups: &std::collections::HashMap<String, Vec<(f64, f64, f64, f64)>>,
    amplitude_threshold: f64,
) -> Vec<Lump> {
    let delta_angle_rad = DEFAULT_DELTA_ANGLE;
    let angle_window_deg = delta_angle_rad.to_degrees();
    let amp_thr = amplitude_threshold.max(0.01);
    let mut aggregated = Vec::new();

    for (wtype, comps) in wave_groups {
        let mut comps: Vec<(f64, f64, f64, f64)> = comps.iter()
            .filter(|c| c.2 >= amp_thr)
            .cloned().collect();
        if comps.is_empty() { continue; }
        comps.sort_by(|a, b| a.0.partial_cmp(&b.0).unwrap());

        // Cluster nearby components
        let mut clusters: Vec<Vec<(f64, f64, f64, f64)>> = Vec::new();
        let mut cur = vec![comps[0]];
        for item in comps.iter().skip(1) {
            let (t_i, sigma_i, amp_i, alpha_i) = *item;
            let (t_p, sigma_p, amp_p, alpha_p) = *cur.last().unwrap();
            let ang_ok = (alpha_i - alpha_p).abs() <= delta_angle_rad;
            let time_ok = (t_i - t_p).abs() <= 2.0 * sigma_i + 2.0 * sigma_p;
            let ratio = (amp_i + 1e-9) / (amp_p + 1e-9);
            let amp_ok = if wtype.to_uppercase() == "P" { ratio.ln() <= 3.0f64.ln() }
                else if wtype.to_uppercase() == "T" { ratio.ln() >= 0.33f64.ln() }
                else { true };
            if ang_ok && time_ok && amp_ok { cur.push(*item); }
            else { clusters.push(cur.clone()); cur = vec![*item]; }
        }
        clusters.push(cur);

        // QRS sub-labelling references
        let mut peak_times = Vec::new();
        let mut peak_amps_vec = Vec::new();
        let mut peak_angles_vec = Vec::new();
        if wtype.to_uppercase() == "QRS" {
            for cl in &clusters {
                let best = cl.iter().max_by(|a, b| a.2.partial_cmp(&b.2).unwrap()).unwrap();
                let idx_c = nearest_idx(t_ms, best.0);
                peak_times.push(best.0);
                peak_amps_vec.push(best.2);
                peak_angles_vec.push(vy[idx_c].atan2(vx[idx_c]));
            }
        }

        for (idx_cl, cl) in clusters.iter().enumerate() {
            let best = cl.iter().max_by(|a, b| a.2.partial_cmp(&b.2).unwrap()).unwrap();
            let (t_peak, amp_peak, angle_peak) = find_true_peak(
                t_ms, vx, vy, best.0, best.1, angle_window_deg,
            );
            let name = generate_subwave_name(
                wtype, idx_cl, clusters.len(),
                &peak_times, &peak_amps_vec, &peak_angles_vec,
            );
            let start_time = cl.iter().map(|(t, s, _, _)| t - 2.0 * s).fold(f64::MAX, f64::min);
            let end_time = cl.iter().map(|(t, s, _, _)| t + 2.0 * s).fold(f64::MIN, f64::max);
            let sigma = (end_time - start_time) / 4.0;

            aggregated.push(Lump {
                wave_type: name,
                start_time: (start_time * 1000.0).round() / 1000.0,
                peak_time: (t_peak * 1000.0).round() / 1000.0,
                end_time: (end_time * 1000.0).round() / 1000.0,
                amplitude_mv: (amp_peak * 1000.0).round() / 1000.0,
                angle_rad: (angle_peak * 1000.0).round() / 1000.0,
                angle_deg: (angle_peak.to_degrees() * 1000.0).round() / 1000.0,
                center_ms: t_peak,
                sigma_ms: sigma,
            });
        }
    }
    aggregated
}

