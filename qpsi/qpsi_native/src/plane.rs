// 1) time_to_region_label (wave_classification.py:64-86)
// ---------------------------------------------------------------------------
fn time_to_region_label(t_ecg: f64, rr_ms: f64, offset_ms: f64) -> &'static str {
    if t_ecg >= -offset_ms {
        let frac = t_ecg / rr_ms;
        if t_ecg < QRS_FRAC_MS { return "QRS"; }
        if frac < ST_FRAC { return "ST"; }
        if frac < T_EARLY_FRAC { return "Early-T"; }
        if frac < T_NORMAL_FRAC { return "Normal-T"; }
        "Late-T"
    } else {
        if t_ecg < EARLY_P_MS { return "Early-P"; }
        if t_ecg < NORMAL_P_MS { return "Normal-P"; }
        "Late-P"
    }
}

// ---------------------------------------------------------------------------
// 2) unify_wave_type (wave_classification.py:89-105)
// ---------------------------------------------------------------------------
fn unify_wave_type(raw: &str) -> String {
    let name = raw.to_lowercase();
    let stripped = if name.starts_with("early-") { &name[6..] }
        else if name.starts_with("normal-") { &name[7..] }
        else if name.starts_with("late-") { &name[5..] }
        else { &name };
    if stripped.starts_with('p') { "P".to_string() }
    else if stripped.starts_with('t') { "T".to_string() }
    else if stripped.starts_with("qrs") { "QRS".to_string() }
    else { raw.to_string() }
}

// ---------------------------------------------------------------------------
// 3) find_true_peak (wave_classification.py:112-154)
// ---------------------------------------------------------------------------
fn find_true_peak(
    t_ms: &[f64], vx: &[f64], vy: &[f64],
    t0: f64, sigma0: f64, angle_window_deg: f64,
) -> (f64, f64, f64) {
    let n = t_ms.len();
    let idx0 = nearest_idx(t_ms, t0);

    let dt_ms = if n > 1 { t_ms[1] - t_ms[0] } else { 1.0 };
    let angle_ctr = vy[idx0].atan2(vx[idx0]);
    let win_rad = (2.0 * sigma0 / dt_ms).round().max(1.0) as usize;
    let lo = idx0.saturating_sub(win_rad);
    let hi = (idx0 + win_rad).min(n - 1);

    let angle_window_rad = angle_window_deg.to_radians();
    let mut best_idx = idx0;
    let mut best_mag = 0.0f64;
    let mut found_any = false;

    for i in lo..=hi {
        let ang_i = vy[i].atan2(vx[i]);
        // angle_diff = |angle(exp(j*(ang_i - angle_ctr)))|
        let diff = (ang_i - angle_ctr).sin().atan2((ang_i - angle_ctr).cos()).abs();
        if diff <= angle_window_rad {
            let mag = (vx[i] * vx[i] + vy[i] * vy[i]).sqrt();
            if mag > best_mag || !found_any {
                best_mag = mag;
                best_idx = i;
                found_any = true;
            }
        }
    }

    let amp_peak = (vx[best_idx] * vx[best_idx] + vy[best_idx] * vy[best_idx]).sqrt();
    let angle_peak = vy[best_idx].atan2(vx[best_idx]);
    (t_ms[best_idx], amp_peak, angle_peak)
}

