// 4) _choose_r_cluster (wave_classification.py:161-182)
// ---------------------------------------------------------------------------
fn choose_r_cluster(peak_amps: &[f64], peak_angles: &[f64]) -> usize {
    let ang_lo = (-20.0f64).to_radians();
    let ang_hi = 90.0f64.to_radians();
    let cands: Vec<usize> = peak_angles.iter().enumerate()
        .filter(|(_, &a)| a >= ang_lo && a <= ang_hi)
        .map(|(i, _)| i)
        .collect();
    if !cands.is_empty() {
        *cands.iter().max_by(|&&a, &&b| peak_amps[a].partial_cmp(&peak_amps[b]).unwrap()).unwrap()
    } else {
        peak_amps.iter().enumerate()
            .max_by(|(_, a), (_, b)| a.partial_cmp(b).unwrap())
            .map(|(i, _)| i).unwrap_or(0)
    }
}

