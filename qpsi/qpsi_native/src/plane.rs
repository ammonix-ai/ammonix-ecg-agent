// 8) st_measure (wave_classification.py:393-428)
// ---------------------------------------------------------------------------
fn st_measure(t_ms: &[f64], vx: &[f64], vy: &[f64], lumps: &[Lump]) -> (f64, f64, f64) {
    let s_end = lumps.iter()
        .find(|l| l.wave_type.to_uppercase() == "S")
        .map(|l| l.end_time);
    let r_end = lumps.iter()
        .find(|l| l.wave_type.to_uppercase() == "R")
        .map(|l| l.end_time);
    let s_end = s_end.or(r_end).unwrap_or(0.0);
    let st_time = s_end + 60.0;
    let idx = nearest_idx(t_ms, st_time);
    let amp = (vx[idx] * vx[idx] + vy[idx] * vy[idx]).sqrt();
    let angle_deg = vy[idx].atan2(vx[idx]).to_degrees();
    (st_time, amp, angle_deg)
}

