/// Process ALL beats for BOTH planes entirely in Rust with rayon parallelism.
///
/// This replaces the entire per-beat loop in pipeline.py step 7.
/// GIL is released once at entry, rayon parallelizes all beats, GIL
/// reacquired only when returning results to Python.
///
/// Input:
///   beats_seg6_flat: (n_beats, 6, n_samples) flattened — raw 6-lead per beat
///   beats_time_ms_flat: (n_beats, n_samples) flattened — time axes per beat
///   n_beats, n_samples: dimensions
///   e2_limb: 2x6 projection matrix for limb plane (flattened)
///   e2_chest: 2x6 projection matrix for chest plane (flattened)
///   g_limb, g_chest: scalar gains per plane
///   not_noisy: noise flag
///   amp_thr_unscaled: amplitude threshold
///   rr_ms_per_beat: RR interval per beat
///   offset_ms: timing offset
///   n_extra: extra Gaussians for hybrid fitter
///
/// Returns list of dicts per beat: [{beat_idx, plane, wave_type, ...}]
#[pyfunction]
pub fn analyse_beats_full_rust<'py>(
    py: Python<'py>,
    beats_seg6_flat: PyReadonlyArray1<'py, f64>,
    beats_time_ms_flat: PyReadonlyArray1<'py, f64>,
    n_beats: usize,
    sample_counts: PyReadonlyArray1<'py, f64>,  // per-beat sample counts
    e2_limb_flat: PyReadonlyArray1<'py, f64>,
    e2_chest_flat: PyReadonlyArray1<'py, f64>,
    g_limb: f64,
    g_chest: f64,
    not_noisy: bool,
    amp_thr_unscaled: f64,
    rr_ms_per_beat: PyReadonlyArray1<'py, f64>,
    offset_ms: f64,
    n_extra: usize,
) -> PyResult<Bound<'py, PyList>> {
    let seg6_all = beats_seg6_flat.as_slice()?.to_vec();
    let time_all = beats_time_ms_flat.as_slice()?.to_vec();
    let rr_all = rr_ms_per_beat.as_slice()?.to_vec();
    let sc = sample_counts.as_slice()?.to_vec();
    let e2l = e2_limb_flat.as_slice()?;
    let e2c = e2_chest_flat.as_slice()?;

    // Build projection matrices
    let e2_limb: [[f64; 6]; 2] = [
        [e2l[0], e2l[1], e2l[2], e2l[3], e2l[4], e2l[5]],
        [e2l[6], e2l[7], e2l[8], e2l[9], e2l[10], e2l[11]],
    ];
    let e2_chest: [[f64; 6]; 2] = [
        [e2c[0], e2c[1], e2c[2], e2c[3], e2c[4], e2c[5]],
        [e2c[6], e2c[7], e2c[8], e2c[9], e2c[10], e2c[11]],
    ];

    // Compute per-beat offsets for variable-length beats
    let mut seg6_offsets = vec![0usize; n_beats + 1];
    let mut time_offsets = vec![0usize; n_beats + 1];
    for i in 0..n_beats {
        let ns = sc[i] as usize;
        seg6_offsets[i + 1] = seg6_offsets[i] + 6 * ns;  // (6, ns) flattened
        time_offsets[i + 1] = time_offsets[i] + ns;
    }

    // Each task: (beat_idx, plane_idx) where plane_idx 0=limb, 1=chest
    let total_tasks = n_beats * 2;

    let results: Vec<(usize, usize, Vec<Lump>)> = (0..total_tasks)
        .into_par_iter()
        .map(|task_idx| {
            let beat_idx = task_idx / 2;
            let plane_idx = task_idx % 2;
            let ns = sc[beat_idx] as usize;

            let seg6 = &seg6_all[seg6_offsets[beat_idx]..seg6_offsets[beat_idx + 1]];
            let t_ms = &time_all[time_offsets[beat_idx]..time_offsets[beat_idx + 1]];
            let rr_ms = rr_all[beat_idx];

            let (e2, g) = if plane_idx == 0 {
                (&e2_limb, g_limb)
            } else {
                (&e2_chest, g_chest)
            };

            let lumps = analyse_plane_single(
                seg6, t_ms, ns, e2, g,
                not_noisy, amp_thr_unscaled, rr_ms, offset_ms, n_extra,
            );

            (beat_idx, plane_idx, lumps)
        })
        .collect();

    // Convert to Python list of dicts
    let py_list = PyList::empty(py);
    for (beat_idx, plane_idx, lumps) in &results {
        let plane_name = if *plane_idx == 0 { "limb" } else { "chest" };
        for lump in lumps {
            let d = PyDict::new(py);
            d.set_item("beat_idx", *beat_idx)?;
            d.set_item("plane", plane_name)?;
            d.set_item("wave_type", lump.wave_type.as_str())?;
            d.set_item("start_time", lump.start_time)?;
            d.set_item("peak_time", lump.peak_time)?;
            d.set_item("end_time", lump.end_time)?;
            d.set_item("amplitude_mV", lump.amplitude_mv)?;
            d.set_item("angle", lump.angle_rad)?;
            d.set_item("angle_degrees", lump.angle_deg)?;
            d.set_item("center_ms", lump.center_ms)?;
            d.set_item("sigma_ms", lump.sigma_ms)?;
            py_list.append(d)?;
        }
    }

    Ok(py_list.into())
}
