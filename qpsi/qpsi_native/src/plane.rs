// 5) generate_subwave_name (wave_classification.py:185-223)
// ---------------------------------------------------------------------------
fn generate_subwave_name(
    wtype: &str, idx: usize, n_sub: usize,
    peak_times: &[f64], peak_amps: &[f64], peak_angles: &[f64],
) -> String {
    let wt = wtype.to_uppercase();
    if wt == "QRS" {
        let idx_r = choose_r_cluster(peak_amps, peak_angles);
        if idx == idx_r { return "R".to_string(); }
        if idx < idx_r {
            let q_num = idx_r - idx;
            return if q_num == 1 { "Q".to_string() } else { format!("Q{}", q_num) };
        }
        let s_num = idx - idx_r;
        return if s_num == 1 { "S".to_string() } else { format!("S{}", s_num) };
    }
    if wt == "T" {
        return if idx == 0 { "T".to_string() } else { format!("T{}", idx + 1) };
    }
    if wt == "P" {
        return if idx == n_sub - 1 { "P".to_string() } else { format!("preP{}", n_sub - 1 - idx) };
    }
    format!("{}{}", wt, idx + 1)
}

