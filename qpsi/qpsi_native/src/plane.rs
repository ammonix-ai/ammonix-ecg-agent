// 9) Full _analyse_plane for one beat (plane_analysis.py:75-308)
// ---------------------------------------------------------------------------
fn analyse_plane_single(
    seg6: &[f64],  // (6, n_samples) flattened
    t_ms: &[f64],
    n_samples: usize,
    e2: &[[f64; 6]; 2],  // projection matrix
    g_plane: f64,
    not_noisy: bool,
    amplitude_threshold_unscaled: f64,
    rr_ms: f64,
    offset_ms: f64,
    n_extra: usize,
) -> Vec<Lump> {
    // 4) Direction from projection: v2 = (g_plane * E2) @ seg6
    let mut vx = vec![0.0f64; n_samples];
    let mut vy = vec![0.0f64; n_samples];
    for j in 0..n_samples {
        for k in 0..6 {
            let s = seg6[k * n_samples + j];
            vx[j] += g_plane * e2[0][k] * s;
            vy[j] += g_plane * e2[1][k] * s;
        }
    }

    let mags: Vec<f64> = (0..n_samples).map(|i| (vx[i]*vx[i] + vy[i]*vy[i]).sqrt()).collect();
    let mag_max = mags.iter().cloned().fold(0.0f64, f64::max);
    if mag_max < 1e-3 { return Vec::new(); }

    // Spike isolation + amplitude threshold
    let (v2c_x, v2c_y, amp_thr) = if not_noisy {
        // Clean signal: use raw, reuse mag_max
        (vx.clone(), vy.clone(), amplitude_threshold_unscaled * mag_max)
    } else {
        let eps = 1e-6;
        let mut sorted_mags = mags.clone();
        sorted_mags.sort_by(|a, b| a.partial_cmp(b).unwrap());
        let clip_thr = sorted_mags[sorted_mags.len() / 2];
        let mut clipped_max = 0.0f64;
        let cx: Vec<f64> = (0..n_samples).map(|i| {
            let clip_amt = (mags[i] - clip_thr / 2.0).max(0.0);
            vx[i] / (mags[i] + eps) * clip_amt
        }).collect();
        let cy: Vec<f64> = (0..n_samples).map(|i| {
            let clip_amt = (mags[i] - clip_thr / 2.0).max(0.0);
            let uy = vy[i] / (mags[i] + eps) * clip_amt;
            let m = (cx[i]*cx[i] + uy*uy).sqrt();
            if m > clipped_max { clipped_max = m; }
            uy
        }).collect();
        // Recompute clipped max properly
        let cm: f64 = (0..n_samples).map(|i| (cx[i]*cx[i] + cy[i]*cy[i]).sqrt()).fold(0.0f64, f64::max);
        (cx, cy, amplitude_threshold_unscaled * cm)
    };

    // Timing windows
    let lhs_lo = -0.5 * rr_ms + offset_ms;
    let lhs_hi = -offset_ms;
    let _qrs_lo = -offset_ms;
    let _qrs_hi = 120.0;
    let rhs_lo = 90.0;
    let rhs_hi = 0.5 * rr_ms;

    // Pack v2c as flat [x0..xN, y0..yN] for fitting
    let mut v2c_flat: Vec<f64> = Vec::with_capacity(2 * n_samples);
    v2c_flat.extend_from_slice(&v2c_x);
    v2c_flat.extend_from_slice(&v2c_y);

    // Full hybrid Gaussian fitting — entirely in Rust
    use crate::hybrid::{fit_gaussians_hybrid_subrange, subtract_fitted_2d};

    let t_ms = t_ms.to_vec();
    let qrs_lo = -offset_ms;
    let qrs_hi = 120.0;
    let rhs_lo = 90.0;
    let rhs_hi = 0.5 * rr_ms;

    // QRS fitting
    let w_qrs = fit_gaussians_hybrid_subrange(
        &t_ms, &v2c_x, &v2c_y,
        qrs_lo, qrs_hi, QRS_N_WAVES, n_extra, amp_thr,
        QRS_SIGMA_MAX, QRS_ANGLE_LAMBDA, QRS_AMP_LAMBDA,
        false, 0, 0.5, // refine_sigmas=false, n_restarts=0
    );

    // Subtract QRS, fit T on residual
    let (res_x, res_y) = subtract_fitted_2d(&t_ms, &v2c_x, &v2c_y, &w_qrs);
    let w_t = fit_gaussians_hybrid_subrange(
        &t_ms, &res_x, &res_y,
        rhs_lo, rhs_hi, T_N_WAVES, n_extra, amp_thr,
        T_SIGMA_MAX, T_ANGLE_LAMBDA, T_AMP_LAMBDA,
        false, 0, 0.5, // refine_sigmas=false, n_restarts=0
    );

    // P-wave fitting on original signal
    let w_p_raw = fit_gaussians_hybrid_subrange(
        &t_ms, &v2c_x, &v2c_y,
        lhs_lo, lhs_hi, P_N_WAVES, n_extra, amp_thr,
        P_SIGMA_MAX, P_ANGLE_LAMBDA, P_AMP_LAMBDA,
        false, 0, 0.5, // refine_sigmas=false, n_restarts=0
    );

    // P-wave cleanup: only keep within (-rr_ms/2 + offset_ms, -PAD_HEAD_R_MS)
    let mut w_p = Vec::new();
    for i in 0..(w_p_raw.len() / 4) {
        let t0_p = w_p_raw[4 * i];
        if t0_p >= (-rr_ms / 2.0 + offset_ms) && t0_p <= (-PAD_HEAD_R_MS) {
            w_p.extend_from_slice(&w_p_raw[4*i..4*i+4]);
        }
    }

    // Concatenate all params
    let mut params = Vec::new();
    params.extend_from_slice(&w_t);
    params.extend_from_slice(&w_qrs);
    params.extend(&w_p);

    // P1: Pacing spike detection — paired from plane_analysis.py:224-239
    // Check fitted Gaussians for narrow sigma + large amplitude in P-wave window
    let mut pacing_detected = false;
    let n_gauss = params.len() / 4;
    for i in 0..n_gauss {
        let t0_i = params[4 * i];
        let sigma_i = params[4 * i + 1];
        let amp_i = params[4 * i + 2].abs();
        // Pacing window: [-250, -50] ms, narrow sigma, large amplitude
        if t0_i >= -250.0 && t0_i <= -50.0
            && sigma_i <= PACE_SIGMA_MS
            && amp_i >= PACE_AMP_MV
        {
            pacing_detected = true;
            break;
        }
    }

    // Wave classification
    let mut lumps = {
        let wave_groups = build_aggregator_input(&params, offset_ms, rr_ms, amp_thr);
        aggregate_waves_by_type(&t_ms, &v2c_x, &v2c_y, &wave_groups, amp_thr)
    };
    // Attach pacing flag to the lump list (Python side reads it)
    if pacing_detected {
        lumps.push(Lump {
            wave_type: "PACING".into(),
            start_time: 0.0, peak_time: 0.0, end_time: 0.0,
            amplitude_mv: 0.0, angle_rad: 0.0, angle_deg: 0.0,
            center_ms: 0.0, sigma_ms: 0.0,
        });
    }
    lumps
}

